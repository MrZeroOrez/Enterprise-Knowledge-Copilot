"""Semantic retrieval module for Enterprise Knowledge Copilot.

Queries ChromaDB vector collection using query embeddings generated by Gemini
with task_type='RETRIEVAL_QUERY'. Returns top-k matching chunks with similarity
distances and citation metadata for downstream grounded RAG generation (Phase 4 & 5).
"""

from __future__ import annotations

import logging
from pathlib import Path
from typing import Any

from src.config import AppConfig, load_config
from src.embeddings import embed_query
from src.vector_store import query_vector_store

logger = logging.getLogger(__name__)


def search_chunks(
    query: str,
    top_k: int = 5,
    where: dict[str, Any] | None = None,
    collection_name: str | None = None,
    persist_dir: Path | str | None = None,
    config: AppConfig | None = None,
    embedding_client: Any | None = None,
    client: Any | None = None,
) -> list[dict[str, Any]]:
    """Search for the most relevant document chunks matching a user query.

    Flow:
        query text -> embed_query (RETRIEVAL_QUERY task_type)
        -> ChromaDB vector search (cosine distance) -> ranked chunks with metadata.

    Args:
        query: User search question or query text.
        top_k: Number of most relevant chunks to return (must be > 0).
        where: Optional metadata filter dict (e.g. {"source": "handbook.pdf"}).
        collection_name: Optional target collection name.
        persist_dir: Optional custom database persistence path.
        config: Optional loaded AppConfig.
        embedding_client: Optional pre-instantiated Gemini client (for unit testing).

    Returns:
        List of dictionaries sorted by relevance:
        [
            {
                "chunk_id": "...",
                "text": "...",
                "source": "...",
                "page": 1,
                "distance": 0.123,
                "metadata": {...}
            },
            ...
        ]

    Raises:
        ValueError: If query is empty/whitespace or top_k is <= 0.
        EmbeddingError: If embedding generation fails.
    """
    if not isinstance(query, str):
        raise ValueError(f"Query must be a string, got: {type(query).__name__}")

    if not query.strip():
        raise ValueError("Query string cannot be empty or whitespace.")

    if not isinstance(top_k, int) or top_k <= 0:
        raise ValueError(f"top_k must be a positive integer (> 0), got: {top_k}")

    app_config = config or load_config()

    # 1. Generate query embedding with task_type='RETRIEVAL_QUERY'
    query_vector = embed_query(
        query=query,
        api_key=app_config.gemini_api_key,
        model=app_config.embedding_model,
        client=embedding_client or client,
    )

    # 2. Query ChromaDB collection
    hits = query_vector_store(
        query_embedding=query_vector,
        top_k=top_k,
        where=where,
        collection_name=collection_name or app_config.chroma_collection_name,
        persist_dir=persist_dir or app_config.chroma_persist_dir,
    )

    return hits
